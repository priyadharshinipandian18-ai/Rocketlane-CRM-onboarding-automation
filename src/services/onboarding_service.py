import json
from datetime import date
from typing import Any

from src.config.database_config import db_pool
from src.models.dto.comms_context import OnboardingCommsContext
from src.models.entities import Onboarding
from src.models.enums import OnboardingStatus, PlanTierCode, PlanTierSource
from src.services.base_service import BaseService


class OnboardingService(BaseService[Onboarding]):
    def __init__(self) -> None:
        super().__init__(Onboarding)

    async def create(
        self,
        onboarding_id: str,
        inbound_email_id: str,
        customer_name: str,
        customer_contact_email: str,
        customer_contact_name: str | None,
        ae_id: str | None,
        sf_opportunity_id: str | None,
        extra_details: dict[str, Any],
    ) -> Onboarding | None:
        """One row per closed deal. ``onboarding_id`` is generated by the caller
        (not left to ``gen_random_uuid()``) so it's known before this INSERT —
        it's needed to build the graph's ``thread_id`` (``onboarding-<id>``)
        *before* the graph runs the node that performs this insert.

        ``UNIQUE sf_opportunity_id`` is the business-level dedup for an AE
        accidentally re-sending the same deal in a second email. Returns
        ``None`` if ``sf_opportunity_id`` already exists.
        """
        return await self.fetch_one(
            """
            INSERT INTO app.onboardings
                (id, inbound_email_id, customer_name, customer_contact_name,
                 customer_contact_email, ae_id, sf_opportunity_id, extra_details)
            VALUES (%s, %s, %s, %s, %s, %s, %s, %s)
            ON CONFLICT (sf_opportunity_id) DO NOTHING
            RETURNING *
            """,
            (
                onboarding_id, inbound_email_id, customer_name, customer_contact_name,
                customer_contact_email, ae_id, sf_opportunity_id, json.dumps(extra_details),
            ),
        )

    async def set_plan_tier(
        self, onboarding_id: str, plan_tier: PlanTierCode | str, source: PlanTierSource | str = PlanTierSource.VOICE_CALL
    ) -> None:
        await self.execute(
            """
            UPDATE app.onboardings
            SET plan_tier = %s, plan_tier_source = %s, plan_confirmed_at = now(),
                status = 'tier_confirmed', updated_at = now()
            WHERE id = %s
            """,
            (PlanTierCode(plan_tier).value, PlanTierSource(source).value, onboarding_id),
        )

    async def set_team_and_dates(
        self, onboarding_id: str, csm_id: str | None, manager_id: str | None, start_date: date, target_go_live_date: date
    ) -> None:
        await self.execute(
            """
            UPDATE app.onboardings
            SET csm_id = %s, manager_id = %s, start_date = %s, target_go_live_date = %s, updated_at = now()
            WHERE id = %s
            """,
            (csm_id, manager_id, start_date, target_go_live_date, onboarding_id),
        )

    async def update_status(
        self, onboarding_id: str, status: OnboardingStatus | str, status_reason: str | None = None
    ) -> None:
        await self.execute(
            "UPDATE app.onboardings SET status = %s, status_reason = %s, updated_at = now() WHERE id = %s",
            (OnboardingStatus(status).value, status_reason, onboarding_id),
        )

    async def list_by_status(self, status: OnboardingStatus | str | None = None, limit: int = 50) -> list[Onboarding]:
        if status is None:
            return await self.find_all(order_by="-created_at", limit=limit)
        return await self.find_all(order_by="-created_at", limit=limit, status=OnboardingStatus(status).value)

    async def get_comms_context(self, onboarding_id: str) -> OnboardingCommsContext | None:
        """Joined read model for the Slack channel personalisation."""
        pool = await db_pool.get_pool()
        async with pool.connection() as conn:
            row = await (await conn.execute(
                """
                SELECT o.id, o.customer_name, o.customer_contact_name, o.customer_contact_email,
                       o.start_date, o.target_go_live_date,
                       t.display_name AS tier_name, t.duration_days, t.csm_model,
                       t.slack_channel_prefix, t.welcome_message_template,
                       csm.name AS csm_name, csm.email AS csm_email, csm.slack_user_id AS csm_slack_user_id,
                       mgr.name AS manager_name, mgr.email AS manager_email, mgr.slack_user_id AS manager_slack_user_id,
                       ae.name AS ae_name, ae.email AS ae_email, ae.slack_user_id AS ae_slack_user_id,
                       rp.project_url
                FROM app.onboardings o
                JOIN app.plan_tiers t ON t.code = o.plan_tier
                LEFT JOIN app.cs_team_members csm ON csm.id = o.csm_id
                LEFT JOIN app.cs_team_members mgr ON mgr.id = o.manager_id
                LEFT JOIN app.account_executives ae ON ae.id = o.ae_id
                LEFT JOIN app.rocketlane_projects rp ON rp.onboarding_id = o.id
                WHERE o.id = %s
                """,
                (onboarding_id,),
            )).fetchone()
        return OnboardingCommsContext.from_row(row)
